# ---------------- Change-failure calibration ----------------
with st.container(border=True):
    theme.panel_header("Calibration", "Change-Failure Model: Calibration and PR-AUC",
                        "Is a deploy the model calls '70% risky' actually risky 70% of the time?", accent="coral")
    cf = report["change_failure_calibration"]
    theme.assumption_note(
        "Baseline PR-AUC is the no-skill value a random classifier would achieve in "
        "expectation -- equal to the positive class's prevalence in the test set, not a "
        "second model trained for comparison."
    )
    st.markdown(
        '<div class="stat-grid">'
        + theme.stat_card("PR-AUC (average precision)", f"{cf['average_precision']:.3f}" if cf.get("average_precision") is not None else "n/a")
        + theme.stat_card("No-skill baseline PR-AUC", f"{cf['baseline_average_precision']:.3f}" if cf.get("baseline_average_precision") is not None else "n/a")
        + theme.stat_card("Holdout ROC-AUC", f"{cf['holdout_roc_auc']:.3f}" if cf.get("holdout_roc_auc") is not None else "n/a")
        + theme.stat_card("Test-set positive rate", f"{cf['positive_rate_test']:.1%}" if cf.get("positive_rate_test") is not None else "n/a")
        + "</div>",
        unsafe_allow_html=True,
    )
    if cf.get("calibration_curve"):
        curve = cf["calibration_curve"]
        chart_df = pd.DataFrame({
            "predicted probability": curve["predicted_probability"],
            "observed frequency (model)": curve["observed_frequency"],
            "perfect calibration": curve["predicted_probability"],
        }).set_index("predicted probability").sort_index()
        st.caption("Perfectly calibrated would track the diagonal exactly")
        st.line_chart(chart_df)
    else:
        st.caption("Calibration curve unavailable for this run (too few positive examples in the test split).")

# ---------------- Change-point detection ----------------
with st.container(border=True):
    theme.panel_header("Early Warning", "Change-Point Detection Backtest", "CUSUM on incoming alert rate, backtested per service against known incident start times", accent="blue")
    cp = report["change_point_detection"]
    cp_df = pd.DataFrame([
        {"service": svc, "n_incidents": d["n_incidents"], "n_detections": d["n_detections"],
         "detection_rate": d["detection_rate"], "false_positive_rate": d["false_positive_rate"],
         "median_lead_minutes": d["median_lead_minutes"]}
        for svc, d in cp.items()
    ])
    if len(cp_df):
        st.dataframe(
            cp_df.style.format({
                "detection_rate": lambda v: f"{v:.0%}" if pd.notna(v) else "n/a",
                "false_positive_rate": lambda v: f"{v:.0%}" if pd.notna(v) else "n/a",
                "median_lead_minutes": lambda v: f"{v:.0f} min" if pd.notna(v) else "n/a",
            }),
            width="stretch", hide_index=True,
        )
        rates = cp_df["detection_rate"].dropna()
        fprs = cp_df["false_positive_rate"].dropna()
        leads = cp_df["median_lead_minutes"].dropna()
        st.markdown(
            '<div class="stat-grid">'
            + theme.stat_card("Fleet detection rate", f"{rates.mean():.0%}" if len(rates) else "n/a", "mean across services")
            + theme.stat_card("Fleet false-positive rate", f"{fprs.mean():.0%}" if len(fprs) else "n/a")
            + theme.stat_card("Median lead time", f"{leads.mean():.0f} min" if len(leads) else "n/a")
            + "</div>",
            unsafe_allow_html=True,
        )
    else:
        st.caption("No change-point backtest data in this report.")

