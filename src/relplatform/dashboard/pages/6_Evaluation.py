EVAL_REPORT_PATH = ROOT / "data" / "eval_report.json"


@st.cache_data
def _load_eval_report(_mtime: float) -> dict:
    return json.loads(EVAL_REPORT_PATH.read_text())


def _confusion_dataframe(cm: dict) -> pd.DataFrame:
    labels = cm["labels"]
    short = [l.replace("_", " ") for l in labels]
    df = pd.DataFrame(cm["matrix"], index=short, columns=short)
    df.index.name = "actual \\ predicted"
    return df


def _heatmap_cell_style(value, vmax: float) -> str:
    """Manual dark-surface-to-accent-blue interpolation, no matplotlib: Styler's
    background_gradient needs it, and it's not a project dependency -- deliberately, to
    keep the Streamlit Community Cloud free-tier memory footprint down."""
    t = 0.0 if vmax <= 0 else min(1.0, value / vmax)
    r = round(23 + t * (94 - 23))
    g = round(31 + t * (200 - 31))
    b = round(49 + t * (242 - 49))
    text = "#05110F" if t > 0.55 else "#EDF1F5"
    return f"background-color: rgb({r},{g},{b}); color: {text};"


def _confusion_styler(df: pd.DataFrame):
    vmax = float(df.to_numpy().max()) if df.size else 0.0
    return df.style.map(lambda v: _heatmap_cell_style(v, vmax))


