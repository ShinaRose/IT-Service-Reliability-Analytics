"""Evaluation tab: does this platform's AI and analytics actually work. Every number on
this page is read verbatim from data/eval_report.json -- a committed file regenerated
offline by scripts/run_eval.py, never recomputed here. That's deliberate: several of
these numbers (AI classification accuracy, retrieval precision, the change-point
backtest) involve either a real LLM call or a resampled eval set, so recomputing them on
every page load would make the numbers jitter for no reason and, for the AI-dependent
ones, cost real tokens on every visitor. Re-run the script and commit the new JSON to
update this page.
"""
